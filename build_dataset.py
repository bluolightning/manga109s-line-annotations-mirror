#!/usr/bin/env python3
"""
build_dataset.py

Companion CLI tool for the Manga109-s text line annotations.

Provides reconstruction of full ground truth text from official Manga109-s
and multi-format dataset export (YOLO, COCO, Manga109 XML, and OCR).

Works with datasets prepared via `process_manga109s.py` from the `kha-white/manga-ocr` project.

Subcommands:
  reconstruct   : Rehydrate official dialogue text into complete verified_data.json
  export-yolo   : Export Ultralytics YOLOv8/YOLO11 line detection or segmentation dataset
  export-coco   : Export standard COCO instances JSON for benchmark evaluations
  export-xml    : Update Manga109 XML files by inserting <line> elements under <text>
  export-ocr    : Export crop-level line OCR dataset mapping crops to ordered line texts
  verify        : Verify consistency and 0 CER between annotations and local Manga109-s

Usage Examples:
  # 1. Reconstruct verified_data.json from local Manga109-s:
  uv run python build_dataset.py reconstruct --manga109-root manga109s-v2026 --output verified_data_reconstructed.json

  # 2. Export YOLO line detector on full manga pages:
  uv run python build_dataset.py export-yolo --manga109-root manga109s-v2026 --target page --output-dir dataset_yolo_pages

  # 3. Export YOLO line detector on bubble crops (crops/ generated by process_manga109s.py):
  uv run python build_dataset.py export-yolo --manga109-root manga109s-v2026 --target crop --output-dir dataset_yolo_crops

  # 4. Export standard COCO instances JSON:
  uv run python build_dataset.py export-coco --manga109-root manga109s-v2026 --output manga109s_coco.json

  # 5. Export enhanced Manga109 XMLs with <line> tags:
  uv run python build_dataset.py export-xml --manga109-root manga109s-v2026 --output-dir manga109s_line_xmls
"""

import argparse
import csv
import json
import os
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple


def find_manga109_sources(
    manga109_root: Optional[Path] = None,
    data_csv_path: Optional[Path] = None,
    frames_csv_path: Optional[Path] = None,
) -> Tuple[Optional[Path], Optional[Path], Optional[Path], Optional[Path], Optional[Path]]:
    """
    Locates data.csv, frames.csv, annotations dir, crops dir, and images dir
    within manga109_root or provided paths.
    """
    resolved_data_csv = data_csv_path
    resolved_frames_csv = frames_csv_path
    resolved_ann_dir: Optional[Path] = None
    resolved_crops_dir: Optional[Path] = None
    resolved_images_dir: Optional[Path] = None

    if manga109_root and manga109_root.exists():
        if not resolved_data_csv:
            candidates = [
                manga109_root / "data.csv",
                manga109_root / "dataset" / "data.csv",
            ]
            for c in candidates:
                if c.exists():
                    resolved_data_csv = c
                    break

        if not resolved_frames_csv:
            candidates = [
                manga109_root / "frames.csv",
                manga109_root / "dataset" / "frames.csv",
            ]
            for c in candidates:
                if c.exists():
                    resolved_frames_csv = c
                    break

        ann_candidates = [
            manga109_root / "annotations",
            manga109_root / "annotations.v2021.12.30",
            manga109_root,
        ]
        for a in ann_candidates:
            if a.exists() and any(a.glob("*.xml")):
                resolved_ann_dir = a
                break

        crops_candidates = [
            manga109_root / "crops",
            manga109_root / "dataset" / "crops",
        ]
        for cr in crops_candidates:
            if cr.exists() and cr.is_dir():
                resolved_crops_dir = cr
                break

        img_candidates = [
            manga109_root / "images",
            manga109_root / "dataset" / "images",
            manga109_root / "dataset" / "manga109_pages" / "images",
        ]
        for im in img_candidates:
            if im.exists() and im.is_dir():
                resolved_images_dir = im
                break

    return (
        resolved_data_csv,
        resolved_frames_csv,
        resolved_ann_dir,
        resolved_crops_dir,
        resolved_images_dir,
    )


def load_text_and_splits(
    manga109_root: Optional[Path] = None,
    data_csv_path: Optional[Path] = None,
) -> Tuple[Dict[str, str], Dict[str, str], Dict[str, Dict[str, Any]]]:
    """
    Loads:
      1. text_lookup: crop_id -> raw dialogue text
      2. split_lookup: crop_id -> split name ('train', 'test', 'val')
      3. meta_lookup: crop_id -> {book, page_index, page_path, page_width, page_height, xmin, ymin, xmax, ymax}
    """
    text_lookup: Dict[str, str] = {}
    split_lookup: Dict[str, str] = {}
    meta_lookup: Dict[str, Dict[str, Any]] = {}

    data_csv, _, ann_dir, _, _ = find_manga109_sources(manga109_root, data_csv_path)

    # for data.csv (from process_manga109s.py)
    if data_csv and data_csv.exists():
        print(f"[Loader] Loading dialogue text and splits from CSV: {data_csv}")
        with open(data_csv, "r", encoding="utf-8", newline="") as f:
            reader = csv.DictReader(f)
            for row in reader:
                cid = row["id"]
                text_lookup[cid] = row.get("text", "")
                if "split" in row:
                    split_lookup[cid] = row["split"]
                meta_lookup[cid] = {
                    "book": row.get("book", ""),
                    "page_index": int(row["page_index"]) if row.get("page_index") else 0,
                    "page_path": row.get("page_path", ""),
                    "page_width": int(row["page_width"]) if row.get("page_width") else 0,
                    "page_height": int(row["page_height"]) if row.get("page_height") else 0,
                    "xmin": int(row["xmin"]) if row.get("xmin") else 0,
                    "ymin": int(row["ymin"]) if row.get("ymin") else 0,
                    "xmax": int(row["xmax"]) if row.get("xmax") else 0,
                    "ymax": int(row["ymax"]) if row.get("ymax") else 0,
                }
        print(f"[Loader] Loaded {len(text_lookup)} text entries from CSV.")
        return text_lookup, split_lookup, meta_lookup

    # Or the regular XML annotations
    if ann_dir and ann_dir.exists():
        xml_files = list(ann_dir.glob("*.xml"))
        if xml_files:
            print(f"[Loader] Parsing dialogue text from {len(xml_files)} Manga109 XML files in {ann_dir}...")
            for xf in xml_files:
                try:
                    tree = ET.parse(xf)
                    root = tree.getroot()
                    book_title = root.attrib.get("title", xf.stem)
                    for page_elem in root.findall(".//page"):
                        p_idx = int(page_elem.attrib.get("index", 0))
                        p_w = int(page_elem.attrib.get("width", 0))
                        p_h = int(page_elem.attrib.get("height", 0))
                        for text_elem in page_elem.findall("text"):
                            cid = text_elem.attrib.get("id")
                            if cid:
                                text_lookup[cid] = text_elem.text or ""
                                meta_lookup[cid] = {
                                    "book": book_title,
                                    "page_index": p_idx,
                                    "page_path": f"images/{book_title}/{p_idx:03d}.jpg",
                                    "page_width": p_w,
                                    "page_height": p_h,
                                    "xmin": int(text_elem.attrib.get("xmin", 0)),
                                    "ymin": int(text_elem.attrib.get("ymin", 0)),
                                    "xmax": int(text_elem.attrib.get("xmax", 0)),
                                    "ymax": int(text_elem.attrib.get("ymax", 0)),
                                }
                except Exception as e:
                    print(f"Warning: Failed to parse {xf.name}: {e}")
            print(f"[Loader] Loaded {len(text_lookup)} text entries from XML annotations.")
            return text_lookup, split_lookup, meta_lookup

    raise FileNotFoundError(
        "Could not find Manga109 text source. Please provide --manga109-root or --data-csv."
    )


def slice_lines_for_crop(raw_gt_text: str, line_lengths: List[int]) -> List[str]:
    """
    Slices raw Manga109 dialogue text into exact line strings using character lengths.
    Strips carriage returns and internal newlines so slicing aligns with line_lengths.
    """
    clean_gt = raw_gt_text.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "")
    idx = 0
    lines = []
    for l_len in line_lengths:
        lines.append(clean_gt[idx : idx + l_len])
        idx += l_len
    return lines


def load_annotations_file(labels_path: Path) -> Dict[str, Any]:
    """Loads stripped or verified annotations file."""
    if not labels_path.exists():
        # Check common fallback names
        candidates = [
            labels_path,
            labels_path.parent / "line_annotations.json",
            labels_path.parent / "manga109s_line_annotations.json",
            labels_path.parent / "manga109s_line_labels.json",
            labels_path.parent / "verified_data.json",
        ]
        for c in candidates:
            if c.exists():
                labels_path = c
                break

    if not labels_path.exists():
        raise FileNotFoundError(f"Annotations file not found: {labels_path}")

    print(f"[Loader] Loading annotations from: {labels_path}")
    with open(labels_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if isinstance(data, list):
        data = {item.get("page_path", f"page_{i}"): item for i, item in enumerate(data) if item}

    return data


def reconstruct_dataset(
    labels: Dict[str, Any],
    text_lookup: Dict[str, str],
    output_path: Path,
    verify_cer: bool = True,
) -> Dict[str, Any]:
    """Reconstructs full verified_data.json with ground-truth dialogue text filled in."""
    reconstructed: Dict[str, Any] = {}
    total_crops = 0
    total_lines = 0
    cer_mismatches = 0

    for page_path, page_entry in labels.items():
        rec_page = {
            "book": page_entry.get("book", ""),
            "page_index": page_entry.get("page_index", 0),
            "page_path": page_path,
            "width": page_entry.get("width", 0),
            "height": page_entry.get("height", 0),
            "texts": [],
        }
        if "verified_at" in page_entry:
            rec_page["verified_at"] = page_entry["verified_at"]

        for text_entry in page_entry.get("texts", []):
            total_crops += 1
            cid = text_entry["id"]
            raw_gt = text_lookup.get(cid, "")
            line_lengths = text_entry.get("line_lengths", [])

            sliced_lines = slice_lines_for_crop(raw_gt, line_lengths)
            full_crop_text = "\n".join(sliced_lines)

            # Check CER against raw ground truth, should be 0 if done properly
            clean_gt = raw_gt.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "")
            clean_rec = full_crop_text.replace("\n", "")
            if clean_rec != clean_gt:
                cer_mismatches += 1

            rec_lines = []
            for idx, line in enumerate(text_entry.get("lines", [])):
                total_lines += 1
                line_text = sliced_lines[idx] if idx < len(sliced_lines) else ""
                rec_line = {
                    "line_index": line.get("line_index", idx),
                    "xmin": line.get("xmin", 0),
                    "ymin": line.get("ymin", 0),
                    "xmax": line.get("xmax", 0),
                    "ymax": line.get("ymax", 0),
                    "text": line_text,
                    "class": line.get("class", ""),
                }
                if "polygon" in line and line["polygon"]:
                    rec_line["polygon"] = line["polygon"]
                rec_lines.append(rec_line)

            rec_crop = {
                "id": cid,
                "xmin": text_entry.get("xmin", 0),
                "ymin": text_entry.get("ymin", 0),
                "xmax": text_entry.get("xmax", 0),
                "ymax": text_entry.get("ymax", 0),
                "text": full_crop_text,
                "lines": rec_lines,
                "line_lengths": line_lengths,
            }
            if text_entry.get("auto_approved"):
                rec_crop["auto_approved"] = True

            rec_page["texts"].append(rec_crop)

        reconstructed[page_path] = rec_page

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(reconstructed, f, ensure_ascii=False, indent=2)

    print("=" * 60)
    print("Reconstruction Complete:")
    print(f"  Output file:          {output_path}")
    print(f"  Total pages:          {len(reconstructed)}")
    print(f"  Total crops:          {total_crops}")
    print(f"  Total lines:          {total_lines}")
    print(f"  CER Discrepancies:    {cer_mismatches}")
    print("=" * 60)

    if verify_cer and cer_mismatches > 0:
        raise ValueError(f"Reconstruction failed verification: {cer_mismatches} crops had CER discrepancies!")
    else:
        print("VERIFIED: 100% exact text rehydration with 0 CER discrepancies!")

    return reconstructed


def export_yolo(
    labels: Dict[str, Any],
    output_dir: Path,
    split_lookup: Dict[str, str],
    target: str = "page",
    task: str = "detect",
    margin: int = 10,
    manga109_root: Optional[Path] = None,
    include_images: bool = False,
) -> None:
    """
    Exports YOLOv8/YOLO11 line detection or segmentation dataset.
    
    Modes:
      target == 'page': Line bboxes/polygons relative to full manga page images.
      target == 'crop': Line bboxes/polygons relative to speech bubble crops (crops/{id}.png).
    """
    labels_dir = output_dir / "labels"
    images_dir = output_dir / "images"

    for s in ["train", "val"]:
        (labels_dir / s).mkdir(parents=True, exist_ok=True)
        if include_images:
            (images_dir / s).mkdir(parents=True, exist_ok=True)

    _, _, _, crops_dir, images_src_dir = find_manga109_sources(manga109_root)

    counts = {"train": 0, "val": 0}
    total_annotations = 0

    if target == "page":
        for page_path, page_entry in labels.items():
            width = page_entry.get("width", 1)
            height = page_entry.get("height", 1)
            if width <= 0: width = 1
            if height <= 0: height = 1

            crops = page_entry.get("texts", [])
            # Determine split from data.csv split or hash
            page_split = "train"
            if crops and crops[0]["id"] in split_lookup:
                raw_s = split_lookup[crops[0]["id"]]
                page_split = "val" if raw_s in ["test", "val"] else "train"
            else:
                # Deterministic 90/10 hash split
                h = abs(hash(page_path)) % 10
                page_split = "val" if h == 0 else "train"

            counts[page_split] += 1
            book = page_entry.get("book", "")
            p_idx = page_entry.get("page_index", 0)
            page_stem = f"{book}_{p_idx:03d}"
            txt_path = labels_dir / page_split / f"{page_stem}.txt"

            lines_out = []
            for text_entry in crops:
                for line in text_entry.get("lines", []):
                    total_annotations += 1
                    if task == "segment" and "polygon" in line and len(line["polygon"]) == 8:
                        poly = line["polygon"]
                        coords_norm = []
                        for i in range(0, 8, 2):
                            px = max(0.0, min(float(poly[i]) / width, 1.0))
                            py = max(0.0, min(float(poly[i+1]) / height, 1.0))
                            coords_norm.append(f"{px:.6f}")
                            coords_norm.append(f"{py:.6f}")
                        lines_out.append(f"0 {' '.join(coords_norm)}")
                    else:
                        xmin = max(0, line.get("xmin", 0))
                        ymin = max(0, line.get("ymin", 0))
                        xmax = min(width, line.get("xmax", 0))
                        ymax = min(height, line.get("ymax", 0))
                        xc = ((xmin + xmax) / 2.0) / width
                        yc = ((ymin + ymax) / 2.0) / height
                        w = max(0.0, (xmax - xmin)) / width
                        h = max(0.0, (ymax - ymin)) / height
                        lines_out.append(f"0 {xc:.6f} {yc:.6f} {w:.6f} {h:.6f}")

            with open(txt_path, "w", encoding="utf-8") as f:
                f.write("\n".join(lines_out) + "\n")

            # Link or copy image if requested
            if include_images and images_src_dir:
                src_img = images_src_dir / book / f"{p_idx:03d}.jpg"
                if src_img.exists():
                    dst_img = images_dir / page_split / f"{page_stem}.jpg"
                    if not dst_img.exists():
                        try:
                            os.symlink(src_img.resolve(), dst_img)
                        except Exception:
                            shutil.copy2(src_img, dst_img)

    elif target == "crop":
        # relative to crops/{id}.png with margin
        for page_path, page_entry in labels.items():
            page_w = page_entry.get("width", 1)
            page_h = page_entry.get("height", 1)

            for text_entry in page_entry.get("texts", []):
                cid = text_entry["id"]
                raw_s = split_lookup.get(cid, "train")
                crop_split = "val" if raw_s in ["test", "val"] else "train"
                counts[crop_split] += 1

                # Calculate crop coordinates with margin matching process_manga109s.py
                t_xmin = text_entry.get("xmin", 0)
                t_ymin = text_entry.get("ymin", 0)
                t_xmax = text_entry.get("xmax", 0)
                t_ymax = text_entry.get("ymax", 0)

                c_xmin = max(t_xmin - margin, 0)
                c_ymin = max(t_ymin - margin, 0)
                c_xmax = min(t_xmax + margin, page_w)
                c_ymax = min(t_ymax + margin, page_h)
                crop_w = max(1, c_xmax - c_xmin)
                crop_h = max(1, c_ymax - c_ymin)

                txt_path = labels_dir / crop_split / f"{cid}.txt"
                lines_out = []

                for line in text_entry.get("lines", []):
                    total_annotations += 1
                    if task == "segment" and "polygon" in line and len(line["polygon"]) == 8:
                        poly = line["polygon"]
                        coords_norm = []
                        for i in range(0, 8, 2):
                            px_rel = poly[i] - c_xmin
                            py_rel = poly[i+1] - c_ymin
                            px_norm = max(0.0, min(px_rel / crop_w, 1.0))
                            py_norm = max(0.0, min(py_rel / crop_h, 1.0))
                            coords_norm.append(f"{px_norm:.6f}")
                            coords_norm.append(f"{py_norm:.6f}")
                        lines_out.append(f"0 {' '.join(coords_norm)}")
                    else:
                        lx1 = max(0, line.get("xmin", 0) - c_xmin)
                        ly1 = max(0, line.get("ymin", 0) - c_ymin)
                        lx2 = min(crop_w, line.get("xmax", 0) - c_xmin)
                        ly2 = min(crop_h, line.get("ymax", 0) - c_ymin)
                        xc = ((lx1 + lx2) / 2.0) / crop_w
                        yc = ((ly1 + ly2) / 2.0) / crop_h
                        w = max(0.0, (lx2 - lx1)) / crop_w
                        h = max(0.0, (ly2 - ly1)) / crop_h
                        lines_out.append(f"0 {xc:.6f} {yc:.6f} {w:.6f} {h:.6f}")

                with open(txt_path, "w", encoding="utf-8") as f:
                    f.write("\n".join(lines_out) + "\n")

                if include_images and crops_dir:
                    src_crop = crops_dir / f"{cid}.png"
                    if src_crop.exists():
                        dst_crop = images_dir / crop_split / f"{cid}.png"
                        if not dst_crop.exists():
                            try:
                                os.symlink(src_crop.resolve(), dst_crop)
                            except Exception:
                                shutil.copy2(src_crop, dst_crop)

    yaml_train_path = "images/train" if include_images else "labels/train"
    yaml_val_path = "images/val" if include_images else "labels/val"
    yaml_content = f"""# Ultralytics YOLO Manga Line Detection Dataset
# Target: {target} | Task: {task}
path: {output_dir.resolve().as_posix()}
train: {yaml_train_path}
val: {yaml_val_path}

names:
  0: text_line
"""
    with open(output_dir / "dataset.yaml", "w", encoding="utf-8") as f:
        f.write(yaml_content)

    print("=" * 60)
    print(f"YOLO Dataset Export Complete ({target}-level, task={task}):")
    print(f"  Directory:         {output_dir}")
    print(f"  Train items:       {counts['train']}")
    print(f"  Val items:         {counts['val']}")
    print(f"  Total annotations: {total_annotations}")
    print(f"  dataset.yaml:      {output_dir / 'dataset.yaml'}")
    print("=" * 60)


def export_coco(
    labels: Dict[str, Any],
    text_lookup: Dict[str, str],
    output_path: Path,
    target: str = "page",
    margin: int = 10,
) -> None:
    """Exports standard COCO instances JSON format."""
    images = []
    annotations = []
    categories = [
        {"id": 1, "name": "text_line", "supercategory": "text"},
        {"id": 2, "name": "text_block", "supercategory": "text"},
    ]

    image_id = 0
    ann_id = 0

    if target == "page":
        for page_path, page_entry in labels.items():
            image_id += 1
            width = int(page_entry.get("width", 0))
            height = int(page_entry.get("height", 0))

            images.append({
                "id": image_id,
                "file_name": page_path,
                "width": width,
                "height": height,
                "book": page_entry.get("book", ""),
                "page_index": page_entry.get("page_index", 0),
            })

            for text_entry in page_entry.get("texts", []):
                cid = text_entry["id"]
                t_xmin = int(text_entry.get("xmin", 0))
                t_ymin = int(text_entry.get("ymin", 0))
                t_xmax = int(text_entry.get("xmax", 0))
                t_ymax = int(text_entry.get("ymax", 0))
                t_w = max(0, t_xmax - t_xmin)
                t_h = max(0, t_ymax - t_ymin)

                # Bubble / text_block annotation
                ann_id += 1
                annotations.append({
                    "id": ann_id,
                    "image_id": image_id,
                    "category_id": 2,
                    "bbox": [t_xmin, t_ymin, t_w, t_h],
                    "area": t_w * t_h,
                    "iscrowd": 0,
                    "crop_id": cid,
                })

                # Line annotations
                raw_gt = text_lookup.get(cid, "")
                line_lengths = text_entry.get("line_lengths", [])
                sliced_lines = slice_lines_for_crop(raw_gt, line_lengths) if raw_gt else []

                for idx, line in enumerate(text_entry.get("lines", [])):
                    ann_id += 1
                    l_xmin = int(line.get("xmin", 0))
                    l_ymin = int(line.get("ymin", 0))
                    l_xmax = int(line.get("xmax", 0))
                    l_ymax = int(line.get("ymax", 0))
                    l_w = max(0, l_xmax - l_xmin)
                    l_h = max(0, l_ymax - l_ymin)

                    if "polygon" in line and len(line["polygon"]) == 8:
                        seg = [[int(p) for p in line["polygon"]]]
                    else:
                        seg = [[l_xmin, l_ymin, l_xmax, l_ymin, l_xmax, l_ymax, l_xmin, l_ymax]]

                    line_text = sliced_lines[idx] if idx < len(sliced_lines) else ""
                    ann_dict = {
                        "id": ann_id,
                        "image_id": image_id,
                        "category_id": 1,
                        "bbox": [l_xmin, l_ymin, l_w, l_h],
                        "segmentation": seg,
                        "area": l_w * l_h,
                        "iscrowd": 0,
                        "crop_id": cid,
                        "line_index": line.get("line_index", idx),
                    }
                    if line_text:
                        ann_dict["text"] = line_text
                    if line.get("class"):
                        ann_dict["class"] = line["class"]

                    annotations.append(ann_dict)

    elif target == "crop":
        for page_path, page_entry in labels.items():
            page_w = int(page_entry.get("width", 0))
            page_h = int(page_entry.get("height", 0))

            for text_entry in page_entry.get("texts", []):
                image_id += 1
                cid = text_entry["id"]
                t_xmin = int(text_entry.get("xmin", 0))
                t_ymin = int(text_entry.get("ymin", 0))
                t_xmax = int(text_entry.get("xmax", 0))
                t_ymax = int(text_entry.get("ymax", 0))

                c_xmin = max(t_xmin - margin, 0)
                c_ymin = max(t_ymin - margin, 0)
                c_xmax = min(t_xmax + margin, page_w)
                c_ymax = min(t_ymax + margin, page_h)
                crop_w = max(1, c_xmax - c_xmin)
                crop_h = max(1, c_ymax - c_ymin)

                images.append({
                    "id": image_id,
                    "file_name": f"crops/{cid}.png",
                    "width": crop_w,
                    "height": crop_h,
                    "crop_id": cid,
                    "page_path": page_path,
                })

                raw_gt = text_lookup.get(cid, "")
                line_lengths = text_entry.get("line_lengths", [])
                sliced_lines = slice_lines_for_crop(raw_gt, line_lengths) if raw_gt else []

                for idx, line in enumerate(text_entry.get("lines", [])):
                    ann_id += 1
                    lx1 = max(0, int(line.get("xmin", 0)) - c_xmin)
                    ly1 = max(0, int(line.get("ymin", 0)) - c_ymin)
                    lx2 = min(crop_w, int(line.get("xmax", 0)) - c_xmin)
                    ly2 = min(crop_h, int(line.get("ymax", 0)) - c_ymin)
                    lw = max(0, lx2 - lx1)
                    lh = max(0, ly2 - ly1)

                    if "polygon" in line and len(line["polygon"]) == 8:
                        poly = line["polygon"]
                        poly_crop = []
                        for i in range(0, 8, 2):
                            poly_crop.append(max(0, min(int(poly[i]) - c_xmin, crop_w)))
                            poly_crop.append(max(0, min(int(poly[i+1]) - c_ymin, crop_h)))
                        seg = [poly_crop]
                    else:
                        seg = [[lx1, ly1, lx2, ly1, lx2, ly2, lx1, ly2]]

                    line_text = sliced_lines[idx] if idx < len(sliced_lines) else ""
                    ann_dict = {
                        "id": ann_id,
                        "image_id": image_id,
                        "category_id": 1,
                        "bbox": [lx1, ly1, lw, lh],
                        "segmentation": seg,
                        "area": lw * lh,
                        "iscrowd": 0,
                        "crop_id": cid,
                        "line_index": line.get("line_index", idx),
                    }
                    if line_text:
                        ann_dict["text"] = line_text
                    if line.get("class"):
                        ann_dict["class"] = line["class"]

                    annotations.append(ann_dict)

    coco_dataset = {
        "info": {
            "description": f"Manga109-s Text Line Annotations ({target}-level)",
            "version": "1.0",
        },
        "images": images,
        "annotations": annotations,
        "categories": categories,
    }

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(coco_dataset, f, ensure_ascii=False, indent=2)

    print("=" * 60)
    print(f"COCO Dataset Export Complete ({target}-level):")
    print(f"  Output file:       {output_path}")
    print(f"  Images count:      {len(images)}")
    print(f"  Annotations count: {len(annotations)}")
    print("=" * 60)


def export_xml(
    labels: Dict[str, Any],
    text_lookup: Dict[str, str],
    manga109_root: Path,
    output_dir: Path,
) -> None:
    """Updates official Manga109 XML files by inserting <line> elements under <text>."""
    output_dir.mkdir(parents=True, exist_ok=True)
    _, _, ann_dir, _, _ = find_manga109_sources(manga109_root)
    if not ann_dir:
        raise FileNotFoundError(f"Annotations directory not found in {manga109_root}")

    # Group labels by book
    book_pages: Dict[str, List[Dict[str, Any]]] = {}
    for page_path, page_entry in labels.items():
        book = page_entry.get("book", "")
        if book:
            book_pages.setdefault(book, []).append(page_entry)

    print(f"[XML] Enhancing annotations for {len(book_pages)} books...")
    enhanced_books = 0
    total_lines_inserted = 0

    for book, pages in book_pages.items():
        xml_src = ann_dir / f"{book}.xml"
        if not xml_src.exists():
            continue

        tree = ET.parse(xml_src)
        root = tree.getroot()

        page_dict = {p.get("page_index"): p for p in pages}

        for page_elem in root.findall(".//page"):
            p_idx = int(page_elem.attrib.get("index", -1))
            if p_idx not in page_dict:
                continue

            target_page = page_dict[p_idx]
            crop_lookup = {c["id"]: c for c in target_page.get("texts", [])}

            for text_elem in page_elem.findall("text"):
                cid = text_elem.attrib.get("id")
                if cid not in crop_lookup:
                    continue

                crop_data = crop_lookup[cid]
                raw_gt = text_lookup.get(cid, text_elem.text or "")
                line_lengths = crop_data.get("line_lengths", [])
                sliced_lines = slice_lines_for_crop(raw_gt, line_lengths)

                text_elem.text = "\n".join(sliced_lines)

                # Remove any existing line elements
                for old_line in list(text_elem.findall("line")):
                    text_elem.remove(old_line)

                # Append verified line elements
                for idx, line in enumerate(crop_data.get("lines", [])):
                    total_lines_inserted += 1
                    l_elem = ET.SubElement(text_elem, "line")
                    l_elem.attrib = {
                        "index": str(line.get("line_index", idx)),
                        "xmin": str(line.get("xmin", 0)),
                        "ymin": str(line.get("ymin", 0)),
                        "xmax": str(line.get("xmax", 0)),
                        "ymax": str(line.get("ymax", 0)),
                    }
                    if "polygon" in line and line["polygon"]:
                        l_elem.attrib["polygon"] = ",".join(map(str, line["polygon"]))
                    if line.get("class"):
                        l_elem.attrib["class"] = line["class"]
                    l_elem.text = sliced_lines[idx] if idx < len(sliced_lines) else ""

        out_xml = output_dir / f"{book}.xml"
        tree.write(out_xml, encoding="utf-8", xml_declaration=True)
        enhanced_books += 1

    print("=" * 60)
    print("Manga109 Enhanced XML Export Complete:")
    print(f"  Output directory:       {output_dir}")
    print(f"  Books updated:          {enhanced_books}")
    print(f"  Total <line> tags added: {total_lines_inserted}")
    print("=" * 60)


def export_ocr(
    labels: Dict[str, Any],
    text_lookup: Dict[str, str],
    output_path: Path,
    margin: int = 10,
) -> None:
    """Exports crop-level line OCR dataset (JSONL) mapping crops to ordered lines and text."""
    rows = []
    total_lines = 0

    for page_path, page_entry in labels.items():
        page_w = int(page_entry.get("width", 0))
        page_h = int(page_entry.get("height", 0))

        for text_entry in page_entry.get("texts", []):
            cid = text_entry["id"]
            t_xmin = int(text_entry.get("xmin", 0))
            t_ymin = int(text_entry.get("ymin", 0))
            t_xmax = int(text_entry.get("xmax", 0))
            t_ymax = int(text_entry.get("ymax", 0))

            c_xmin = max(t_xmin - margin, 0)
            c_ymin = max(t_ymin - margin, 0)
            c_xmax = min(t_xmax + margin, page_w)
            c_ymax = min(t_ymax + margin, page_h)
            crop_w = max(1, c_xmax - c_xmin)
            crop_h = max(1, c_ymax - c_ymin)

            raw_gt = text_lookup.get(cid, "")
            line_lengths = text_entry.get("line_lengths", [])
            sliced_lines = slice_lines_for_crop(raw_gt, line_lengths) if raw_gt else []

            crop_lines = []
            for idx, line in enumerate(text_entry.get("lines", [])):
                total_lines += 1
                lx1 = max(0, int(line.get("xmin", 0)) - c_xmin)
                ly1 = max(0, int(line.get("ymin", 0)) - c_ymin)
                lx2 = min(crop_w, int(line.get("xmax", 0)) - c_xmin)
                ly2 = min(crop_h, int(line.get("ymax", 0)) - c_ymin)
                line_text = sliced_lines[idx] if idx < len(sliced_lines) else ""

                item = {
                    "line_index": idx,
                    "bbox_crop": [lx1, ly1, lx2, ly2],
                    "text": line_text,
                    "char_count": len(line_text),
                }
                if "polygon" in line and line["polygon"]:
                    poly = line["polygon"]
                    item["polygon_crop"] = [
                        poly[i] - c_xmin if i % 2 == 0 else poly[i] - c_ymin
                        for i in range(len(poly))
                    ]
                crop_lines.append(item)

            rows.append({
                "id": cid,
                "crop_path": f"crops/{cid}.png",
                "page_path": page_path,
                "crop_bbox_page": [c_xmin, c_ymin, c_xmax, c_ymax],
                "crop_width": crop_w,
                "crop_height": crop_h,
                "text": "\n".join(sliced_lines),
                "lines": crop_lines,
            })

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print("=" * 60)
    print("Crop OCR Dataset Export Complete:")
    print(f"  Output JSONL:     {output_path}")
    print(f"  Crops exported:   {len(rows)}")
    print(f"  Lines exported:   {total_lines}")
    print("=" * 60)


